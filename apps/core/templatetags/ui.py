@register.simple_tag
def icon(name: str, css_class: str = "size-5") -> str:
    path = ICONS.get(name, ICONS["document"])
    return format_html(
        '<svg xmlns="http://www.w3.org/2000/svg" fill="none" viewBox="0 0 24 24" '
        'stroke-width="1.5" stroke="currentColor" class="{}" aria-hidden="true">'
        '<path stroke-linecap="round" stroke-linejoin="round" d="{}"/></svg>',
        css_class,
        path,
    )


@register.filter
def money(value, household=None) -> str:
    """Format a Decimal as currency, e.g. ``1234.5`` -> ``$1,234.50``."""
    if value in (None, ""):
        value = Decimal("0")
    try:
        amount = Decimal(value)
    except (InvalidOperation, TypeError, ValueError):
        return ""
    symbol = household.currency_symbol if household is not None else "$"
    sign = "-" if amount < 0 else ""
    return f"{sign}{symbol}{abs(amount):,.2f}"


STATUS_BADGES = {
    "paid": ("badge-green", "Paid"),
    "partial": ("badge-blue", "Partially paid"),
    "overdue": ("badge-red", "Overdue"),
    "due_soon": ("badge-amber", "Due soon"),
    "unpaid": ("badge-gray", "Upcoming"),
}


@register.simple_tag
def status_badge(status: str) -> str:
    css, label = STATUS_BADGES.get(status, ("badge-gray", status.title()))
    return format_html('<span class="{}">{}</span>', css, label)


@register.simple_tag(takes_context=True)
def nav_active(context, *prefixes: str) -> str:
    """Return ``active`` when the current URL name starts with any prefix."""
    request = context.get("request")
    match = getattr(request, "resolver_match", None)
    if not match:
        return ""
    view_name = match.view_name or ""
    return "active" if any(view_name.startswith(p) for p in prefixes) else ""


@register.filter
def percent_of(value, total) -> int:
    """Integer percentage of ``value`` / ``total`` clamped to 0..100."""
    try:
        value, total = Decimal(value), Decimal(total)
    except (InvalidOperation, TypeError, ValueError):
        return 0
    if total <= 0:
        return 0
    return max(0, min(100, int(value / total * 100)))
